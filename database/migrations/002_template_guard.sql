DELIMITER $$
CREATE TRIGGER IF NOT EXISTS template_version_immutable_update BEFORE UPDATE ON template_versions FOR EACH ROW
BEGIN
 IF OLD.released THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='RELEASED_VERSION_IMMUTABLE'; END IF;
END$$
CREATE TRIGGER IF NOT EXISTS template_version_immutable_delete BEFORE DELETE ON template_versions FOR EACH ROW
BEGIN
 IF OLD.released THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='RELEASED_VERSION_IMMUTABLE'; END IF;
END$$
DELIMITER ;
